export type TierId = "lite" | "standard" | "premium";

export type SubscriptionStatus =
  | "APPROVAL_PENDING"
  | "APPROVED"
  | "ACTIVE"
  | "SUSPENDED"
  | "CANCELLED"
  | "EXPIRED";

export interface Subscriber {
  /** PayPal subscription ID (I-XXXX). */
  id: string;
  name: string;
  email: string;
  tier: TierId;
  status: SubscriptionStatus;
  /** Current monthly price in USD (after any retention discount). */
  priceUsd: number;
  /** List price of the tier, before any discount. */
  listPriceUsd: number;
  createdAt: string;
  /** Simulated product usage the merchant already knows (e.g. from their own app). */
  usage: { boxesReceived: number; skippedLastMonth: boolean; supportTickets: number };
  /** ISO time a pause should end. */
  resumeAt?: string;
  /** ISO time a temporary discount should be restored to list price. */
  discountUntil?: string;
  /** Pending revise approval link (downgrade awaiting the subscriber's PayPal re-consent). */
  pendingRevise?: { toTier: TierId; approveUrl: string; at: string };
  lastSyncedAt?: string;
}

export type ReasonCategory =
  | "too_expensive"
  | "not_using_enough"
  | "temporary_break"
  | "product_issue"
  | "switching_competitor"
  | "moving_or_life_change"
  | "other";

export type OfferType = "pause" | "downgrade" | "discount";

export interface Offer {
  id: string;
  type: OfferType;
  /** pause: months; discount: number of billing cycles */
  months?: number;
  /** downgrade target */
  toTier?: TierId;
  /** discount percent (integer) */
  discountPct?: number;
  /** Short human-readable label generated by the server, e.g. "Pause for 2 months". */
  label: string;
  /** Monthly revenue kept if accepted, vs. cancellation (USD). */
  mrrKeptUsd: number;
  /** Guardrail notes (e.g. "clamped discount 40% → 25% (policy max)"). */
  guardrailNotes: string[];
  status: "proposed" | "accepted" | "declined" | "executing" | "executed" | "awaiting_paypal_approval" | "failed";
  result?: string;
}

export interface ChatMessage {
  role: "subscriber" | "keepalive" | "system";
  text: string;
  at: string;
  offerId?: string;
}

export type SessionOutcome = "open" | "saved" | "cancelled" | "abandoned";

export interface RetentionSession {
  id: string;
  subscriptionId: string;
  channel: "web" | "agent";
  /** Who is speaking for the subscriber when channel = agent (e.g. "Claude (subscriber's agent)"). */
  agentName?: string;
  startedAt: string;
  reason?: ReasonCategory;
  reasonSummary?: string;
  messages: ChatMessage[];
  offers: Offer[];
  outcome: SessionOutcome;
  /** Internal notes from the retention model (shown to the merchant, never to the subscriber). */
  rationale: string[];
  closedAt?: string;
}

export interface AuditEvent {
  id: string;
  at: string;
  type: string;
  subscriptionId?: string;
  summary: string;
  detail?: unknown;
}

export interface StoreShape {
  agentRuns?: Record<string, import("./agents/consumer").AgentRun>;
  config: {
    productId?: string;
    plans: Partial<Record<TierId, string>>;
  };
  subscribers: Subscriber[];
  sessions: RetentionSession[];
  events: AuditEvent[];
  policy?: import("./policy").MerchantPolicy;
  /** Webhook transmission IDs already processed (dedupe). */
  webhookIds: string[];
}
