/*
 * documenting-readmes: the prompt builder and the README checker.
 *
 * index.html loads this file as a classic script (window.ReadmeKit), and the
 * Node scripts load it with require(). Keep it free of dependencies so the
 * page still works when opened straight from disk.
 */
(function (root, factory) {
  const kit = factory();
  if (typeof module === "object" && module.exports) module.exports = kit;
  else root.ReadmeKit = kit;
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";

  // prompt/readme-prompt.md is this template with every fact left empty.
  // tests/kit.test.mjs fails when the two drift apart.
  const TEMPLATE = `You are writing the README.md for the GitHub repository of a website. Within 10 seconds a
first-time visitor should know what the site does, which team built it, and where it is live.
Every statement must be true and checkable.
PROJECT FACTS (fill in)
{{FACTS}}
STRUCTURE, IN THIS ORDER
1. Top block, with nothing above it, in exactly this layout:
     # <Project name>

     **Team <Team name>**

     - <Member 1>
     - <Member 2>

     Live link: [<domain without https://>](<full https URL>)
2. Hero image: the main screenshot inside <p align="center">, width 760, with alt text that
   says what the image shows.
3. Two short paragraphs. The first says what the site does and for whom. The second says
   what the repository contains.
4. "Features": a two-column table (Feature | What it does) with 4-8 rows, written as what a
   visitor gets.
5. "How it works": one sentence, then a Mermaid flowchart in a \`\`\`mermaid block that follows
   a request from the visitor's browser through the app to the data store and any external
   service. Label each node with plain words plus the real component, for example
   "Store posts<br/>Supabase Postgres". Put each app or service in a subgraph. Use dashed
   arrows (-.->) for background or asynchronous flows. Quote any label that contains
   parentheses. Then one paragraph that walks through the diagram.
6. "Screenshots": one sentence on how they were captured (page, viewport size, browser),
   the main screenshot at width 860 with an italic caption, then a two-column HTML table
   with two more screenshots and their captions. Use only the screenshot files listed.
7. "Tech stack": a table of component / purpose / license.
8. "Quick start": prerequisites with versions, then setup commands in fenced code blocks,
   a "Checks" subsection with the lint, test and build commands, and a "Deploy" subsection
   that says where the live site is hosted and how it is deployed.
9. "Repository map": a table of path / what it holds.
10. "Documentation": links to the docs that exist, one sentence each. Leave this section
    out if the repository has no other docs.
11. "Known limits": a plain bullet list. Do not soften or hide limitations.
12. "License": the license name linked to the LICENSE file, and a link to third-party
    notices if that file exists.
STYLE RULES
- Write for someone who has never seen the project. Lead with what the site does, not the
  technology.
- Short sentences, active voice. No buzzwords: no "revolutionary", "seamless",
  "cutting-edge", "powerful", "robust", "leverage".
- Every claim must be true and checkable against the code. If something is untested, say
  so in Known limits. Never invent team members, links, numbers or features.
- No emojis and no em dashes. Use sentence case for headings.
- Use tables for anything with two or more attributes. Use numbered lists only for steps.
- Put all commands in fenced code blocks with a language tag.
- The top half must be readable by a non-developer. Technical detail goes in the lower half.
- No local file paths, usernames, or personal details from the development machine.
- Do not mention any AI assistant or tool used to write the code or the README, and add no
  "generated by" or co-author lines.
- Keep the documentation kit's identity private. Never include its name, repository URL,
  installation path, badge or credit in the output, including links, image text, comments
  and code blocks. Describe only the target project.
OUTPUT
Return only the final README.md in GitHub-flavored Markdown, ready to commit.`;

  // label: the wording used in the prompt. form: the wording on the page, when
  // it differs. prompt: false keeps a field out of the prompt (About section only).
  const FIELDS = [
    { id: "name", label: "Project name", ph: "[project name]", sample: "On Record" },
    { id: "team", label: "Team name", hint: "without the word Team", ph: "[team name]", sample: "Vulcan" },
    { id: "members", label: "Team members", hint: "one per line", ph: "[one name per line]", list: true, rows: 3,
      sample: "Aditya Arnav\nPallab Das\nAditi Akansha" },
    { id: "live", label: "Live link", hint: "full https URL", ph: "[https://...]", sample: "https://onrecord.pallabdas.me/" },
    { id: "promise", label: "One-line description, written as what a visitor gets", form: "One-line description",
      hint: "what a visitor gets", ph: '[e.g. "Every meeting, remembered by who said it."]',
      sample: "Every meeting, remembered by who said it." },
    { id: "audience", label: "Who it is for", ph: "[audience]", sample: "Teams who need to know who decided what" },
    { id: "features", label: "Main features", hint: "one per line", ph: "[list]", list: true, rows: 4,
      sample: "Transcript attributed to each speaker\nAnswers that quote the lines they came from" },
    { id: "flow", label: "How it works, step by step from the visitor's browser", form: "How it works",
      hint: "one step per line, browser first", ph: "[steps, e.g. browser, API, database]", list: true, rows: 4,
      sample: "Browser streams meeting audio\nListener transcribes it\nGraph database stores who said what" },
    { id: "stack", label: "Tech stack and third-party services with licenses", form: "Tech stack and services with licenses",
      hint: "one per line", ph: "[list]", list: true, rows: 3, sample: "React 19 and Vite (MIT)\nTypeScript (Apache-2.0)" },
    { id: "run", label: "How to run it locally (prerequisites and commands)", form: "How to run it locally",
      hint: "prerequisites and commands, one per line", ph: "[prerequisites and commands]", list: true, rows: 3,
      sample: "Node 22\nnpm ci\nnpm run dev" },
    { id: "deploy", label: "Hosting and deployment", ph: "[host and how it deploys]", sample: "Vercel, deployed from the main branch" },
    { id: "limits", label: "Known limits, not supported or not yet tested", form: "Known limits",
      hint: "not supported or not yet tested, one per line", ph: "[list]", list: true, rows: 3,
      sample: "Tested only in desktop Chrome\nEnglish only" },
    { id: "repo", label: "Repo", hint: "owner/repo", ph: "[owner/repo]", sample: "PDGamerSG/On-Record" },
    { id: "shots", label: "Screenshot files available", form: "Screenshot files", hint: "one path per line",
      ph: "[paths, e.g. docs/images/home.png]", list: true, rows: 3, sample: "docs/images/home.png\ndocs/images/dashboard.png" },
    { id: "license", label: "License", ph: '[license, or "all rights reserved"]', sample: "MIT" },
    { id: "topics", label: "Topics", hint: "for the About section, comma separated", ph: "[topics]", prompt: false,
      sample: "react, vite, meeting-notes" },
  ];

  // The facts behind On Record's README, used by "Load example".
  const EXAMPLE = {
    name: "On Record",
    team: "Vulcan",
    members: "Aditya Arnav\nPallab Das\nAditi Akansha",
    live: "https://onrecord.pallabdas.me/",
    promise: "Every meeting, remembered by who said it.",
    audience: "Teams who need to know who decided what in past meetings",
    features: [
      "Transcript attributed to each speaker",
      "Decisions and action items pulled out of each meeting",
      "Answers about past meetings, with the quotes that back them up",
      "Document search across contracts, specs and policies",
      "Demo mode with two bundled meetings",
    ].join("\n"),
    flow: [
      "Meeting audio from a microphone or a file",
      "Listener finds speech, tells voices apart and transcribes (Silero VAD, speaker embeddings, faster-whisper or Saaras)",
      "Gemma 4 extracts decisions and action items",
      "FalkorDB stores meetings, people, utterances, decisions and action items",
      "The assistant retrieves evidence and answers with Gemma 4, citing the lines it used",
      "The web app receives live updates over SSE",
    ].join("\n"),
    stack: [
      "React 19 and Vite (MIT), TypeScript (Apache-2.0) for the web app",
      "Python 3.12 package wsw_brain for the API",
      "FalkorDB graph database, run with Docker Compose",
      "Gemma 4 through Ollama, the Gemini API or Sarvam",
    ].join("\n"),
    run: [
      "Node 20.19, or 22.12 and later",
      "uv for the Python backend",
      "Docker or Colima for the graph database",
      "cd apps/web && npm ci && npm run dev",
      "uv sync --project apps/api --frozen",
      "docker compose up -d --wait falkordb",
    ].join("\n"),
    deploy: "Live at onrecord.pallabdas.me. The hosting setup is not recorded in the repository.",
    limits: [
      "CI does not check the web app yet",
      "No HTTP route starts the meeting ingest pipeline yet",
      "The document API runs as a separate app",
      "Upload jobs are tracked in memory by the serving process",
    ].join("\n"),
    repo: "PDGamerSG/On-Record",
    shots: "apps/web/public/og.jpg\ndocs/images/meeting-room.png\ndocs/images/ask-drawer.png\ndocs/images/graph.png",
    license: "Apache-2.0",
    topics: "meeting-assistant, knowledge-graph, falkordb, gemma, react",
  };

  function listItems(raw) {
    return raw.split(/\r?\n/).map((s) => s.replace(/^[-*•]\s*/, "").trim()).filter(Boolean);
  }

  function buildPrompt(facts) {
    const lines = FIELDS.filter((f) => f.prompt !== false).map((f) => {
      const raw = ((facts && facts[f.id]) || "").trim();
      if (!raw) return `- ${f.label}: ${f.ph}`;
      if (f.list) return `- ${f.label}:\n` + listItems(raw).map((s) => `  - ${s}`).join("\n");
      return `- ${f.label}: ${raw.replace(/\s*\r?\n\s*/g, " ")}`;
    });
    return TEMPLATE.replace("{{FACTS}}", lines.join("\n"));
  }

  // GitHub topics: lowercase letters, digits and hyphens, at most 50 characters.
  // Topics are comma separated, so "knowledge graph" becomes knowledge-graph.
  function parseTopics(raw) {
    return [...new Set((raw || "").split(/[,\n]+/)
      .map((t) => t.trim().toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 50))
      .filter(Boolean))];
  }

  // Single-quoted for Bash and Git Bash. An apostrophe becomes '\'' there.
  function shellQuote(value) {
    return "'" + String(value).replace(/'/g, "'\\''") + "'";
  }

  function buildAboutCommand(facts) {
    const f = facts || {};
    const parts = ["gh repo edit"];
    const repo = (f.repo || "").trim().replace(/^https?:\/\/github\.com\//i, "").replace(/\.git$/, "").replace(/\/$/, "");
    if (repo) parts.push(repo);
    const live = (f.live || "").trim();
    const description = (f.promise || "").trim().replace(/\s*\r?\n\s*/g, " ");
    if (live) parts.push("--homepage " + shellQuote(live));
    if (description) parts.push("--description " + shellQuote(description));
    for (const t of parseTopics(f.topics)) parts.push("--add-topic " + t);
    return parts.length > (repo ? 2 : 1) ? parts.join(" ") : "";
  }

  // ---------- README checker ----------

  const BUZZ = ["revolutionary", "seamless", "seamlessly", "cutting-edge", "cutting edge", "powerful",
    "game-changing", "game changer", "next-generation", "next-gen", "state-of-the-art", "blazing",
    "world-class", "best-in-class", "robust", "leverage", "unleash", "supercharge", "effortless",
    "effortlessly", "groundbreaking", "innovative", "delve", "tapestry", "elevate"];

  // H2 sections in the order the prompt asks for them.
  const SECTIONS = [
    { name: "Features", re: /^##\s.*\bfeatures\b.*$/im, required: true },
    { name: "How it works", re: /^##\s.*how it works.*$/im, required: true },
    { name: "Screenshots", re: /^##\s.*screenshots?\b.*$/im, required: true },
    { name: "Tech stack", re: /^##\s.*(tech stack|built with).*$/im, required: true },
    { name: "Quick start", re: /^##\s.*(quick start|getting started|run (it )?locally).*$/im, required: true },
    { name: "Repository map", re: /^##\s.*(repository map|repo map|project structure).*$/im, required: true },
    { name: "Documentation", re: /^##\s.*documentation.*$/im, required: false },
    { name: "Known limits", re: /^##\s.*known limit.*$/im, required: true },
    { name: "License", re: /^##\s.*licen[cs]e.*$/im, required: true },
  ];

  const MERMAID_TYPES = /^(flowchart|graph|sequenceDiagram|classDiagram|stateDiagram(-v2)?|erDiagram|journey|gantt|pie|C4Context|C4Container|C4Component|C4Dynamic|C4Deployment|mindmap|timeline|gitGraph|quadrantChart|requirementDiagram|sankey-beta|xychart-beta|block-beta|packet-beta|architecture-beta|kanban|radar-beta)\b/;

  const PLACEHOLDERS = FIELDS.map((f) => f.ph);

  // Blank out fenced code (and optionally inline code) without moving any
  // character, so positions found in the masked text also index the original.
  function mask(md, inline) {
    let out = md.replace(/^(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1[ \t]*$/gm, (m) => m.replace(/[^\n]/g, " "));
    if (inline) out = out.replace(/`[^`\n]+`/g, (m) => " ".repeat(m.length));
    return out;
  }

  function findSection(masked, re) {
    const m = masked.match(re);
    if (!m) return null;
    const bodyStart = m.index + m[0].length;
    const next = masked.slice(bodyStart).search(/^#{1,2}\s/m);
    return { start: m.index, bodyStart, end: next === -1 ? masked.length : bodyStart + next };
  }

  function plural(n, word) {
    return `${n} ${word}${n === 1 ? "" : "s"}`;
  }

  function list(items, max) {
    const shown = items.slice(0, max || 5).join(", ");
    return items.length > (max || 5) ? shown + ", …" : shown;
  }

  const IMG_RE = /<img\b[^>]*>|!\[[^\]]*\]\([^)]+\)/gi;

  function checkReadme(input, options) {
    const opts = options || {};
    const md = String(input || "").replace(/^﻿/, "").replace(/\r\n?/g, "\n");
    const masked = mask(md, false);
    const text = mask(md, true);
    const out = [];
    const add = (level, msg, extra) => out.push(Object.assign({ level, text: msg }, extra));

    // Top block: everything above the first H2.
    const firstH2 = masked.search(/^##\s/m);
    const topEnd = firstH2 === -1 ? masked.length : firstH2;
    const top = masked.slice(0, topEnd);

    const firstLine = (top.split("\n").find((l) => l.trim()) || "").trim();
    const h1 = /^#\s+\S/.test(firstLine);
    add(h1 ? "ok" : "bad", h1 ? `Starts with the project name: "${firstLine.replace(/^#\s+/, "")}".`
      : "The first line must be the project name as an H1 (# Name).");

    const team = top.match(/^\*\*Team\s+([^*\n]+?)\*\*[ \t]*$/m);
    add(team ? "ok" : "bad", team ? `Team line found: "Team ${team[1]}".`
      : 'No "**Team <name>**" line under the title.');

    const live = top.match(/^Live link:\s*\[([^\]\n]+)\]\(([^)\s]+)\)[ \t]*$/m);
    if (live) {
      const url = live[2];
      if (!/^https:\/\//i.test(url)) add("warn", `Live link "${url}" should start with https://.`);
      else if (/:\/\//.test(live[1])) add("warn", "Show the domain without https:// as the live link text.");
      else add("ok", `Live link found: ${url}`);
    } else {
      add("bad", 'No "Live link: [domain](https://...)" line in the top block.');
    }

    if (team) {
      const membersEnd = live && live.index > team.index ? live.index : topEnd;
      const n = (top.slice(team.index + team[0].length, membersEnd).match(/^\s*[-*]\s+\S/gm) || []).length;
      add(n ? "ok" : "bad", n ? `${plural(n, "team member")} listed.`
        : "No team members listed as bullets under the team line.");
      if (live && live.index < team.index) add("bad", "The team line must come before the live link.");
    }

    // The hero belongs below the live link (or below the team line or title
    // when those are missing, which the checks above already report).
    const anchor = live ? live.index : team ? team.index : top.search(/^#\s+\S/m);
    const topImages = [...top.matchAll(IMG_RE)].filter((m) => !/shields\.io/i.test(m[0]));
    if (topImages.some((m) => m.index > anchor)) add("ok", "Has a hero image below the top block.");
    else if (topImages.length) add("bad", "The hero image must sit below the live link, not above the top block.");
    else add("bad", "No hero image between the live link and the first section.");

    const noAlt = [...masked.matchAll(IMG_RE)].filter((m) => {
      const tag = m[0];
      if (/shields\.io/i.test(tag)) return false;
      if (tag.startsWith("!")) return /^!\[\s*\]/.test(tag);
      const alt = tag.match(/\balt\s*=\s*("([^"]*)"|'([^']*)')/i);
      return !alt || !(alt[2] || alt[3] || "").trim();
    }).length;
    add(noAlt ? "warn" : "ok", noAlt ? `${plural(noAlt, "image")} without alt text.` : "Every image has alt text.");

    // Sections
    const found = SECTIONS.map((s) => Object.assign({}, s, { at: findSection(masked, s.re) }));
    const missing = found.filter((s) => s.required && !s.at).map((s) => s.name);
    add(missing.length ? "bad" : "ok", missing.length ? `Missing sections: ${missing.join(", ")}.`
      : "All required sections are present.");
    for (const s of found.filter((s) => !s.required && !s.at)) {
      add("warn", `No ${s.name} section. Add one when the repo has docs to link.`);
    }
    const positions = found.filter((s) => s.at).map((s) => s.at.start);
    if (positions.length > 1) {
      const inOrder = positions.every((p, i) => i === 0 || p > positions[i - 1]);
      add(inOrder ? "ok" : "warn", inOrder ? "Sections are in the expected order."
        : "Sections are out of the expected order.");
    }
    const sec = (name) => found.find((s) => s.name === name).at;

    // Architecture diagram
    const how = sec("How it works");
    if (how) {
      const hasDiagram = /^```+\s*mermaid\b/m.test(md.slice(how.bodyStart, how.end));
      add(hasDiagram ? "ok" : "bad", hasDiagram ? "How it works has a Mermaid diagram."
        : "How it works needs a Mermaid diagram (```mermaid).");
    }
    const blocks = [...md.matchAll(/^```+\s*mermaid[^\n]*\n([\s\S]*?)^```+[ \t]*$/gm)].map((m) => m[1]);
    const badType = blocks.filter((b) => !MERMAID_TYPES.test((b.split("\n").find((l) => l.trim() && !/^\s*%%/.test(l)) || "").trim()));
    if (badType.length) add("warn", `${plural(badType.length, "Mermaid block")} does not start with a diagram type such as flowchart or sequenceDiagram.`);
    const parens = blocks.filter((b) => /^\s*(flowchart|graph)\b/m.test(b) && /\w\[(?![("[])[^\]\n]*[()][^\]\n]*\]/.test(b));
    if (parens.length) add("warn", 'A flowchart label contains parentheses without quotes. Write A["Label (detail)"] or GitHub will not render it.');

    // Features table
    const feat = sec("Features");
    if (feat) {
      const rows = masked.slice(feat.bodyStart, feat.end).split("\n")
        .filter((l) => /^\s*\|/.test(l) && !/^\s*\|\s*:?-{2,}/.test(l));
      const n = Math.max(0, rows.length - 1);
      add(n >= 4 && n <= 8 ? "ok" : "warn", `Features table has ${plural(n, "row")}${n >= 4 && n <= 8 ? "." : " (aim for 4-8)."}`);
    }

    // Known limits
    const lim = sec("Known limits");
    if (lim) {
      const n = (masked.slice(lim.bodyStart, lim.end).match(/^\s*[-*]\s+\S/gm) || []).length;
      add(n >= 2 ? "ok" : "warn", `Known limits lists ${plural(n, "item")}${n >= 2 ? "." : ". Be honest; most projects have more."}`);
    }

    // Wording
    const lower = text.toLowerCase();
    const hits = BUZZ.filter((w) => new RegExp("\\b" + w.replace(/-/g, "[- ]") + "\\b", "i").test(lower));
    add(hits.length ? "bad" : "ok", hits.length ? `Buzzwords found: ${hits.join(", ")}.` : "No buzzwords found.");

    const dashes = (text.match(/—/g) || []).length;
    add(dashes ? "warn" : "ok", dashes ? `${plural(dashes, "em dash")}. Use a period or a comma instead.` : "No em dashes.");

    const emojiHeads = (masked.match(/^#{1,6}\s.*$/gm) || []).filter((h) => /\p{Extended_Pictographic}/u.test(h)).length;
    if (emojiHeads) add("warn", `${plural(emojiHeads, "heading")} with an emoji. Plain headings match the On Record style.`);

    // Code blocks
    const fences = md.match(/^```.*$/gm) || [];
    const opens = fences.filter((_, i) => i % 2 === 0);
    const bare = opens.filter((f) => f.trim() === "```").length;
    if (opens.length) add(bare ? "warn" : "ok", bare ? `${plural(bare, "code block")} without a language tag.` : "Every code block has a language tag.");
    else add("warn", "No fenced code blocks. Setup commands belong in them.");

    // Leftovers and private details
    const curly = [...new Set(md.match(/\{\{[^{}\n]{1,60}\}\}/g) || [])];
    const prompts = PLACEHOLDERS.filter((p) => md.includes(p));
    const leftovers = curly.concat(prompts);
    add(leftovers.length ? "bad" : "ok", leftovers.length ? `Unfilled placeholders: ${list(leftovers)}.` : "No unfilled placeholders.");
    if (/<!--\s*kit:/i.test(md)) add("bad", "Template guidance comments (<!-- kit: ... -->) are still in the file.");
    const todo = text.match(/\b(TODO|TBD|FIXME)\b|lorem ipsum/gi);
    if (todo) add("warn", `Unfinished text: ${list([...new Set(todo)])}.`);

    const pathRe = /([A-Za-z]:\\(Users|Documents and Settings)\\[^\s`'"]+)|(\/Users\/[A-Za-z0-9._-]+)|(\/home\/[A-Za-z0-9._-]+)/g;
    const paths = [...new Set(md.match(pathRe) || [])];
    add(paths.length ? "bad" : "ok", paths.length ? `Local paths found: ${list(paths, 3)}` : "No local machine paths.");

    const gen = /co-authored-by|generated (by|with) \[?(chatgpt|claude|copilot|gemini|cursor|codex|windsurf|an? ai\b|ai\b)|written by (chatgpt|claude|copilot|gemini|an? ai\b)/i.test(md);
    add(gen ? "bad" : "ok", gen ? 'Contains a "generated by" or co-author line.' : 'No "generated by" or co-author lines.');

    const kitIdentity = /\breadme[\s_-]*pro[\s_-]*max\b/i.test(md);
    add(kitIdentity ? "bad" : "ok", kitIdentity ? "Contains documentation kit identity. Remove its name, links and credits."
      : "No documentation kit identity in the README.");

    // Relative links, only when the caller can look at the disk.
    if (typeof opts.exists === "function") {
      const targets = [];
      for (const m of masked.matchAll(/\]\(\s*<?([^)\s>]+)>?(?:\s+"[^"]*")?\s*\)|\b(?:src|href)\s*=\s*["']([^"']+)["']/gi)) {
        const raw = (m[1] || m[2] || "").trim();
        if (!raw || /^([a-z][a-z0-9+.-]*:|#|\/\/)/i.test(raw)) continue;
        let p = raw.split("#")[0].split("?")[0].replace(/^\//, "");
        try { p = decodeURIComponent(p); } catch { /* keep the raw path */ }
        if (p) targets.push(p);
      }
      const gone = [...new Set(targets)].filter((p) => !opts.exists(p));
      const n = new Set(targets).size;
      add(gone.length ? "bad" : "ok", gone.length ? `Links to missing files: ${list(gone)}.`
        : n === 0 ? "No local links to check." : n === 1 ? "The one local link points to a file that exists."
        : `All ${n} local links point to files that exist.`);
    }

    add("warn", "Manual check: is every claim true, and do the team, members and live link match the real project?", { manual: true });
    return out;
  }

  function summarize(results) {
    const auto = results.filter((r) => !r.manual);
    return {
      pass: auto.filter((r) => r.level === "ok").length,
      total: auto.length,
      bad: auto.filter((r) => r.level === "bad").length,
      warn: auto.filter((r) => r.level === "warn").length,
    };
  }

  return { TEMPLATE, FIELDS, EXAMPLE, buildPrompt, buildAboutCommand, parseTopics, checkReadme, summarize };
});
